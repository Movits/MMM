base_dir = 'client/src/i18n/locales'
for lang, keys in translations.items():
    filepath = os.path.join(base_dir, f'{lang}.json')
    if not os.path.exists(filepath):
        print(f"⚠️  {lang}.json não encontrado")
        continue
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if 'auth' not in data:
        data['auth'] = {}
    for key, value in keys.items():
        data['auth'][key] = value
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"✅ {lang}.json — {len(keys)} chaves de reset adicionadas")

print("\n🎉 i18n de recuperação de senha concluído!")
